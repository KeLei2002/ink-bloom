(function () {
  const q = new URLSearchParams(location.search).get('lang');
  const nav = (navigator.language || 'en').toLowerCase();
  MR.lang = q === 'zh' || q === 'en' ? q : nav.startsWith('zh') ? 'zh' : 'en';
})();

MR.t = function (key, vars) {
  let s = MR.STR[MR.lang][key];
  if (s === undefined) s = MR.STR.en[key] !== undefined ? MR.STR.en[key] : key;
  if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
  return s;
};
